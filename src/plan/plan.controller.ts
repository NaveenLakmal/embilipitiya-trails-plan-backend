import {
  BadRequestException,
  Body,
  Controller,
  Delete,
  Get,
  Headers,
  HttpCode,
  HttpStatus,
  Param,
  ParseIntPipe,
  Post,
  Put,
} from '@nestjs/common';
import { ApiHeader, ApiOperation, ApiResponse, ApiTags } from '@nestjs/swagger';
import { PlanService } from './plan.service';
import { AddPlanItemDto, ReorderPlanDto } from './dto/plan.dto';

/**
 * All plan endpoints require the x-session-id header.
 * The frontend generates a UUID and stores it in localStorage, then sends
 * it with every request to identify the guest's plan.
 */
@ApiTags('Visit Plan')
@ApiHeader({
  name: 'x-session-id',
  description: 'UUID generated by the browser (stored in localStorage) to identify the guest plan',
  required: true,
})
@Controller('plan')
export class PlanController {
  constructor(private readonly planService: PlanService) {}

  private getSessionId(sessionId: string | undefined): string {
    if (!sessionId || !sessionId.trim()) {
      throw new BadRequestException(
        'x-session-id header is required to identify your plan.',
      );
    }
    return sessionId.trim();
  }

  @Get()
  @ApiOperation({
    summary: 'Get the current session plan with ordered items (full Place data embedded)',
  })
  @ApiResponse({ status: 200, description: 'The plan with embedded place data' })
  getPlan(@Headers('x-session-id') sessionId?: string) {
    return this.planService.getPlan(this.getSessionId(sessionId));
  }

  @Post('items')
  @ApiOperation({ summary: 'Add a place to the plan (max 8, no duplicates)' })
  @ApiResponse({ status: 201, description: 'Plan item created' })
  @ApiResponse({ status: 400, description: 'Duplicate or limit exceeded' })
  @ApiResponse({ status: 404, description: 'Place not found.' })
  addItem(
    @Headers('x-session-id') sessionId: string | undefined,
    @Body() dto: AddPlanItemDto,
  ) {
    return this.planService.addItem(this.getSessionId(sessionId), dto);
  }

  @Delete('items/:planItemId')
  @HttpCode(HttpStatus.NO_CONTENT)
  @ApiOperation({ summary: 'Remove a place from the plan' })
  @ApiResponse({ status: 204, description: 'Item removed' })
  @ApiResponse({ status: 404, description: 'Plan item not found in your plan.' })
  removeItem(
    @Headers('x-session-id') sessionId: string | undefined,
    @Param('planItemId', ParseIntPipe) planItemId: number,
  ) {
    return this.planService.removeItem(this.getSessionId(sessionId), planItemId);
  }

  @Put('order')
  @ApiOperation({
    summary:
      'Persist a new visit order for plan items. Body: { planItemIds: number[] } in the desired order.',
  })
  @ApiResponse({ status: 200, description: 'Updated order returned' })
  reorderItems(
    @Headers('x-session-id') sessionId: string | undefined,
    @Body() dto: ReorderPlanDto,
  ) {
    return this.planService.reorderItems(this.getSessionId(sessionId), dto);
  }

  @Delete()
  @ApiOperation({ summary: 'Clear all items from the current session plan' })
  @ApiResponse({ status: 200, description: 'Plan cleared' })
  clearPlan(@Headers('x-session-id') sessionId?: string) {
    return this.planService.clearPlan(this.getSessionId(sessionId));
  }
}
