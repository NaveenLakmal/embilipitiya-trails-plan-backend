import {
  Entity,
  PrimaryGeneratedColumn,
  Column,
  ManyToOne,
  OneToMany,
  JoinColumn,
  CreateDateColumn,
} from 'typeorm';
import { User } from '../users/user.entity';
import { PlanItem } from './plan-item.entity';

@Entity('visit_plans')
export class VisitPlan {
  @PrimaryGeneratedColumn({ name: 'plan_id' })
  plan_id: number;

  /**
   * user_id is nullable — guest plans are identified by session_id only.
   * It will be linked to a real user once auth is added.
   */
  @Column({ name: 'user_id', nullable: true })
  user_id: number | null;

  @ManyToOne(() => User, (user) => user.plans, {
    nullable: true,
    onDelete: 'SET NULL',
  })
  @JoinColumn({ name: 'user_id' })
  user: User | null;

  /**
   * session_id — UUID generated by the browser (stored in localStorage).
   * Used to identify a guest's plan before auth exists.
   */
  @Column({ name: 'session_id', type: 'varchar', length: 100, unique: true })
  session_id: string;

  @CreateDateColumn({ name: 'created_at' })
  created_at: Date;

  @OneToMany(() => PlanItem, (item) => item.plan, {
    cascade: true,
    eager: false,
  })
  items: PlanItem[];
}
